class Point:
    """Класс, представляющий точку на плоскости.

    Attributes:
        x (float): Координата X.
        y (float): Координата Y.
        id (int): Уникальный идентификатор точки. Отрицательные значения 
                  зарезервированы для супер-треугольника.
        cx (int): Индекс клетки сетки по оси X.
        cy (int): Индекс клетки сетки по оси Y.
        layer (int): Слой иерархии, к которому относится точка.
        subset (int): Подмножество внутри слоя.
    """

    def __init__(self, x: float, y: float, pid: int, cx: int = -1, cy: int = -1):
        """Инициализирует точку.

        Args:
            x: Координата X.
            y: Координата Y.
            pid: Уникальный идентификатор точки.
            cx: Индекс клетки сетки по оси X (по умолчанию -1).
            cy: Индекс клетки сетки по оси Y (по умолчанию -1).
        """
        self.x = x
        self.y = y
        self.id = pid
        self.cx = cx
        self.cy = cy
        self.layer = -1
        self.subset = -1
